export function getBondRank(xp: number): { rank: number; label: string; nextThreshold: number; progressPct: number } {
  const thresholds = [0, 60, 150, 280, 450];
  const labels = ['Acquaintance', 'Friendly Neighbor', 'Trusted Ally', 'Sworn Partner', 'Bataan Legend'];
  let rank = 1;
  for (let i = 1; i < thresholds.length; i++) {
    if (xp >= thresholds[i]) rank = i + 1;
  }
  const currentFloor = thresholds[rank - 1];
  const nextThreshold = thresholds[rank] || thresholds[thresholds.length - 1];
  const progressPct =
    rank >= 5 ? 100 : Math.min(100, Math.round(((xp - currentFloor) / Math.max(1, nextThreshold - currentFloor)) * 100));
  return {
    rank,
    label: labels[rank - 1],
    nextThreshold,
    progressPct,
  };
}

